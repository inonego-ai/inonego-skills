using System;
using System.Collections;
using System.Collections.Generic;

namespace Inonego.Skills.CSharpTool
{

    // ============================================================
    /// <summary>
    /// 선언에 연결된 XML summary의 형식 특성을 기술한다.
    /// </summary>
    // ============================================================
    internal sealed class SummaryDescriptor
    {
        // ------------------------------------------------------------
        /// <summary>
        /// 완결된 summary 태그 쌍이 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool Exists                        = false;

        // ------------------------------------------------------------
        /// <summary>
        /// summary 태그 줄에 본문이 함께 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasInlineTagContent           = false;

        // ------------------------------------------------------------
        /// <summary>
        /// 발견한 summary 시작 태그의 수.
        /// </summary>
        // ------------------------------------------------------------
        public int SummaryBlockCount              = 0;

        // ------------------------------------------------------------
        /// <summary>
        /// 닫히지 않은 summary 블록이 있는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool HasIncompleteSummary          = false;

        // ------------------------------------------------------------
        /// <summary>
        /// summary 본문의 원래 주석 줄 목록.
        /// </summary>
        // ------------------------------------------------------------
        public List<string> RawDescriptionLines   = new();

        // ------------------------------------------------------------
        /// <summary>
        /// summary 본문의 정규화된 설명 목록.
        /// </summary>
        // ------------------------------------------------------------
        public List<string> DescriptionLines      = new();

        // ------------------------------------------------------------
        /// <summary>
        /// 설명 줄마다 br 태그가 있는지 기록한다.
        /// </summary>
        // ------------------------------------------------------------
        public List<bool> DescriptionLineHasBreak = new();

        // ------------------------------------------------------------
        /// <summary>
        /// 상단 구분선 원문.
        /// </summary>
        // ------------------------------------------------------------
        public string TopSeparator                = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// 하단 구분선 원문.
        /// </summary>
        // ------------------------------------------------------------
        public string BottomSeparator             = string.Empty;

        // ------------------------------------------------------------
        /// <summary>
        /// 상단 구분선이 summary에 인접하는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool TopSeparatorAdjacent          = false;

        // ------------------------------------------------------------
        /// <summary>
        /// 하단 구분선이 XML 문서 블록에 인접하는지 여부.
        /// </summary>
        // ------------------------------------------------------------
        public bool BottomSeparatorAdjacent       = false;

        // ------------------------------------------------------------
        /// <summary>
        /// 구분선 밖에서 발견한 XML 문서 주석의 위치.
        /// </summary>
        // ------------------------------------------------------------
        public SourceRange? DocumentationOutsideSeparator = null;

        // ------------------------------------------------------------
        /// <summary>
        /// summary 선언의 원본 위치.
        /// </summary>
        // ------------------------------------------------------------
        public SourceRange Range                  = SourceRange.FromLine(1);
    }

}
